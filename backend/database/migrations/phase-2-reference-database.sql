BEGIN;

CREATE TABLE IF NOT EXISTS brands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    official_website VARCHAR(500),
    country VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_brands_name UNIQUE (name)
);

INSERT INTO brands (name)
SELECT DISTINCT ON (lower(trim(brand))) trim(brand)
FROM products
WHERE brand IS NOT NULL AND trim(brand) <> ''
  AND NOT EXISTS (
      SELECT 1 FROM brands existing_brand
      WHERE lower(existing_brand.name) = lower(trim(products.brand))
  )
ORDER BY lower(trim(brand)), trim(brand)
ON CONFLICT (name) DO NOTHING;

CREATE UNIQUE INDEX IF NOT EXISTS uk_brands_name_ci
    ON brands(lower(name));

ALTER TABLE products
    ADD COLUMN IF NOT EXISTS brand_id BIGINT;

UPDATE products AS product
SET brand_id = brand.id
FROM brands AS brand
WHERE product.brand_id IS NULL
  AND trim(product.brand) = brand.name;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_products_brand'
          AND conrelid = 'public.products'::regclass
    ) THEN
        ALTER TABLE products
            ADD CONSTRAINT fk_products_brand
            FOREIGN KEY (brand_id) REFERENCES brands(id)
            ON DELETE RESTRICT;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_products_brand_id ON products(brand_id);

CREATE TABLE IF NOT EXISTS product_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    version_name VARCHAR(200) NOT NULL,
    version_code VARCHAR(100) NOT NULL,
    release_date DATE,
    description TEXT,
    packaging_details TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_product_versions_product
        FOREIGN KEY (product_id) REFERENCES products(id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_product_version_code UNIQUE (product_id, version_code)
);

CREATE INDEX IF NOT EXISTS idx_product_versions_product_id
    ON product_versions(product_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_product_version_code_ci
    ON product_versions(product_id, lower(version_code));

CREATE TABLE IF NOT EXISTS product_reference_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_version_id BIGINT NOT NULL,
    storage_key VARCHAR(1000) NOT NULL,
    image_url VARCHAR(1000),
    image_type VARCHAR(20) NOT NULL,
    view_type VARCHAR(100),
    original_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reference_images_version
        FOREIGN KEY (product_version_id) REFERENCES product_versions(id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_reference_image_type CHECK (
        image_type IN ('FRONT','BACK','LEFT','RIGHT','TOP','BOTTOM','LOGO','LABEL','BARCODE')
    ),
    CONSTRAINT ck_reference_image_size CHECK (file_size >= 0)
);

CREATE INDEX IF NOT EXISTS idx_reference_images_version_id
    ON product_reference_images(product_version_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_reference_images_storage_key
    ON product_reference_images(storage_key);

COMMIT;
